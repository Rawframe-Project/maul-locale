# Writes src/generated/hanja_finals.h, the final of each Hanja's Korean
# reading as a Korean particle reads it, from the kHangul field of
# Unicode's Unihan database at the version tools/unihan-release.txt pins
# (Unicode License v3, LICENSES/Unicode-3.0.txt). Two bits a code point
# over the CJK blocks (U+3400 to U+4DBF, U+4E00 to U+9FFF, U+F900 to
# U+FAFF): 0 no reading or readings whose finals differ, 1 a vowel, 2 the
# final rieul, 3 another final; four code points a byte, the first in the
# low bits.
#
# usage: gen_hanja_finals.py DIR [--check]
#   DIR      holds Unihan.zip at the pinned version (its SHA-256 is
#            checked)
#   --check  fail when the file differs from what would be written

import hashlib
import io
import os
import sys
import zipfile

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
PATH = os.path.join(ROOT, "src", "generated", "hanja_finals.h")
PIN = os.path.join(ROOT, "tools", "unihan-release.txt")
BLOCKS = [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF)]


def pinned():
    files = {}
    version = ""
    for line in open(PIN, encoding="utf-8"):
        parts = line.split()
        if parts and parts[0] == "file":
            files[parts[1]] = parts[2]
        elif parts and parts[0] == "version":
            version = parts[1]
    return version, files


def final_class(syllable):
    cp = ord(syllable)
    if not 0xAC00 <= cp <= 0xD7A3:
        return 0
    final = (cp - 0xAC00) % 28
    return 1 if final == 0 else 2 if final == 8 else 3


def read(directory):
    version, files = pinned()
    data = open(os.path.join(directory, "Unihan.zip"), "rb").read()
    if hashlib.sha256(data).hexdigest() != files["Unihan.zip"]:
        sys.exit("gen_hanja_finals: Unihan.zip is not the pinned file")
    text = zipfile.ZipFile(io.BytesIO(data)).read("Unihan_Readings.txt").decode("utf-8")
    classes = {}
    for line in text.splitlines():
        parts = line.split("\t")
        if len(parts) != 3 or parts[1] != "kHangul":
            continue
        cp = int(parts[0][2:], 16)
        kinds = {final_class(reading.split(":")[0][-1]) for reading in parts[2].split()}
        classes[cp] = kinds.pop() if len(kinds) == 1 else 0
    return version, classes


def main():
    if len(sys.argv) < 2:
        sys.exit("usage: gen_hanja_finals.py DIR [--check]")
    version, classes = read(sys.argv[1])
    lines = [
        "// SPDX-License-Identifier: MIT AND Unicode-3.0",
        "// Copyright (c) 2026 Sirac Ozmen",
        "// Copyright Unicode, Inc. (the Unihan database)",
        "//",
        "// Generated by tools/gen_hanja_finals.py; do not edit. Each Hanja's",
        "// Korean reading's final as a particle reads it, from Unihan's",
        "// kHangul field, Unicode %s (Unicode License v3," % version,
        "// LICENSES/Unicode-3.0.txt).",
        "// clang-format off",
        "",
        "#ifndef MLOC_GENERATED_HANJA_FINALS_H",
        "#define MLOC_GENERATED_HANJA_FINALS_H",
        "",
        "#include <stdint.h>",
        "",
    ]
    counts = [list(classes.values()).count(kind) for kind in range(4)]
    lines += ["// %d readings: %d without one final, %d vowels, %d rieul, %d others." % (
        len(classes), counts[0], counts[1], counts[2], counts[3]), ""]
    for first, last in BLOCKS:
        size = last - first + 1
        packed = bytearray((size + 3) // 4)
        for cp in range(first, last + 1):
            kind = classes.get(cp, 0)
            packed[(cp - first) // 4] |= kind << ((cp - first) % 4 * 2)
        lines.append("static const uint8_t s_hanjaFinals%04X[%d] = {" % (first, len(packed)))
        for i in range(0, len(packed), 16):
            lines.append("    " + ", ".join("0x%02X" % b for b in packed[i:i + 16]) + ",")
        lines.append("};")
        lines.append("")
    lines += ["#endif", ""]
    text = "\n".join(lines)
    if "--check" in sys.argv[2:]:
        if open(PATH, encoding="utf-8").read() != text:
            sys.exit("gen_hanja_finals: %s is stale" % PATH)
        return
    with open(PATH, "w", encoding="utf-8") as f:
        f.write(text)


if __name__ == "__main__":
    main()
