# Writes src/generated/pow5_tables.h, the powers of five that the
# shortest digits of a double take (src/decimal_shortest.c, after Ulf
# Adams's Ryu): 5^i and 2^k / 5^q to 125 significant bits, as two
# 64-bit words, low first. The table sizes are the largest indexes any
# finite double reaches.
#
# usage: gen_pow5_tables.py [--check | --output-path]
#   --check  fail when the file differs from what would be written
#   --output-path  print the file it writes, relative to the repository's
#                  root (tools/regenerate.sh keeps that file)

import os
import sys

BITS = 125
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
PATH = os.path.join(ROOT, "src", "generated", "pow5_tables.h")


def pow5bits(e):
    # ceil(log2(5^e)) for e >= 1, and 1 for e = 0, as the C side computes it.
    return ((e * 1217359) >> 19) + 1


def log10_pow2(e):
    return (e * 78913) >> 18


def log10_pow5(e):
    return (e * 732923) >> 20


def ranges():
    """The largest q of the inverse table and i of the direct one."""
    inverse = 0
    direct = 0
    for biased in range(0, 2047):
        e2 = (1 if biased == 0 else biased) - 1023 - 52 - 2
        if e2 >= 0:
            inverse = max(inverse, log10_pow2(e2) - (e2 > 3))
        else:
            q = log10_pow5(-e2) - (-e2 > 1)
            direct = max(direct, -e2 - q)
    return inverse, direct


def words(value):
    assert value < 1 << 128
    return value & ((1 << 64) - 1), value >> 64


def text():
    inverse, direct = ranges()
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Copyright (c) 2026 Sirac Ozmen",
        "//",
        "// Generated by tools/gen_pow5_tables.py; do not edit. The powers of",
        "// five the shortest digits of a double take, to 125 significant",
        "// bits, as two 64-bit words, low first.",
        "// clang-format off",
        "",
        "#ifndef MLOC_POW5_TABLES_H",
        "#define MLOC_POW5_TABLES_H",
        "",
        "#include <stdint.h>",
        "",
        "enum",
        "{",
        f"    pow5Bits = {BITS},",
        f"    pow5Count = {direct + 1},",
        f"    pow5InverseCount = {inverse + 1},",
        "};",
        "",
        "// 5^i, shifted to 125 significant bits.",
        "static const uint64_t s_pow5[pow5Count][2] = {",
    ]
    for i in range(direct + 1):
        p = 5 ** i
        shift = pow5bits(i) - BITS
        value = p >> shift if shift > 0 else p << -shift
        low, high = words(value)
        lines.append(f"    {{0x{low:016X}u, 0x{high:016X}u}},")
    lines += ["};", "",
              "// 2^(pow5bits(q) - 1 + 125) / 5^q, rounded up.",
              "static const uint64_t s_pow5Inverse[pow5InverseCount][2] = {"]
    for q in range(inverse + 1):
        value = (1 << (pow5bits(q) - 1 + BITS)) // 5 ** q + 1
        low, high = words(value)
        lines.append(f"    {{0x{low:016X}u, 0x{high:016X}u}},")
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def main():
    if sys.argv[1:] == ["--output-path"]:
        print(os.path.relpath(PATH, ROOT).replace(os.sep, "/"))
        return
    wanted = text()
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        with open(PATH, encoding="utf-8") as f:
            if f.read() != wanted:
                print("src/generated/pow5_tables.h is stale: run tools/gen_pow5_tables.py")
                return 1
        return 0
    with open(PATH, "w", encoding="utf-8") as f:
        f.write(wanted)
    return 0


if __name__ == "__main__":
    sys.exit(main())
