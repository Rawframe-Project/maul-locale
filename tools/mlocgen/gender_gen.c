#include "gender_gen.h"

#include "xml.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

enum
{
    // genderList.xml lists about 60 locales.
    maxLocales = 256,
    // A locale ID's room: "zh_Hant" and its terminator.
    localeRoom = 12,
};

typedef struct Entry
{
    char locale[localeRoom];
    int rule;
} Entry;

static int CompareEntries(const void* a, const void* b)
{
    return strcmp(((const Entry*)a)->locale, ((const Entry*)b)->locale);
}

// The rule's number in src/list_genders.h's order; -1 for none.
static int RuleOf(const char* type)
{
    static const char* const s_rules[3] = {"neutral", "mixedNeutral", "maleTaints"};
    for (int i = 0; i < 3; i++)
    {
        if (type != nullptr && strcmp(type, s_rules[i]) == 0)
        {
            return i;
        }
    }
    return -1;
}

// Adds a personList's locales; false and a message for a bad one.
static bool AddLocales(const char* locales, int rule, Entry* entries, int* count, char* errorOut,
                       size_t errorCapacity)
{
    const char* at = locales;
    while (*at != '\0')
    {
        size_t length = strcspn(at, " \t\n");
        if (length >= localeRoom || *count == maxLocales)
        {
            snprintf(errorOut, errorCapacity, "genderList.xml: locale %.*s does not fit",
                     (int)length, at);
            return false;
        }
        if (length > 0)
        {
            memcpy(entries[*count].locale, at, length);
            entries[*count].locale[length] = '\0';
            entries[*count].rule = rule;
            (*count)++;
        }
        at += length;
        at += strspn(at, " \t\n");
    }
    return true;
}

static int ReadEntries(const XmlNode* root, Entry* entries, char* errorOut, size_t errorCapacity)
{
    const XmlNode* gender = XmlFindChild(root, "gender");
    int count = 0;
    for (int i = 0; gender != nullptr && i < gender->childCount; i++)
    {
        const XmlNode* list = gender->children[i];
        if (strcmp(list->name, "personList") != 0)
        {
            continue;
        }
        int rule = RuleOf(XmlGetAttribute(list, "type"));
        const char* locales = XmlGetAttribute(list, "locales");
        if (rule < 0 || locales == nullptr)
        {
            snprintf(errorOut, errorCapacity, "genderList.xml: a personList without a known type");
            return 0;
        }
        if (!AddLocales(locales, rule, entries, &count, errorOut, errorCapacity))
        {
            return 0;
        }
    }
    qsort(entries, (size_t)count, sizeof(Entry), CompareEntries);
    for (int i = 1; i < count; i++)
    {
        if (strcmp(entries[i - 1].locale, entries[i].locale) == 0)
        {
            snprintf(errorOut, errorCapacity, "genderList.xml lists %s twice", entries[i].locale);
            return 0;
        }
    }
    if (count == 0)
    {
        snprintf(errorOut, errorCapacity, "genderList.xml lists no locale");
    }
    return count;
}

int GenerateListGenders(const char* commonDirectory, char** sourceOut, size_t* sourceSizeOut,
                        char* errorOut, size_t errorCapacity)
{
    char path[4096];
    snprintf(path, sizeof(path), "%s/supplemental/genderList.xml", commonDirectory);
    XmlNode* root = XmlParseFile(path, errorOut, errorCapacity);
    if (root == nullptr)
    {
        return 0;
    }
    Entry entries[maxLocales];
    int count = ReadEntries(root, entries, errorOut, errorCapacity);
    XmlFree(root);
    if (count == 0)
    {
        return 0;
    }
    size_t capacity = 1024 + (size_t)count * 32;
    char* source = malloc(capacity);
    if (source == nullptr)
    {
        snprintf(errorOut, errorCapacity, "out of memory");
        return 0;
    }
    int size = snprintf(source, capacity,
                        "// SPDX-License-Identifier: MIT\n"
                        "// Copyright (c) 2026 Sirac Ozmen\n"
                        "//\n"
                        "// The gender of a list of persons by locale, from\n"
                        "// CLDR's supplemental/genderList.xml, sorted.\n"
                        "// Generated by tools/mlocgen; do not edit.\n"
                        "// clang-format off\n"
                        "\n"
                        "#include \"list_genders.h\"\n"
                        "\n"
                        "const ListGenderRule mlocListGenderRules[] = {\n");
    for (int i = 0; i < count; i++)
    {
        size += snprintf(source + size, capacity - (size_t)size, "    {\"%s\", %d},\n",
                         entries[i].locale, entries[i].rule);
    }
    size += snprintf(source + size, capacity - (size_t)size,
                     "};\n\nconst uint32_t mlocListGenderRuleCount = %d;\n", count);
    *sourceOut = source;
    *sourceSizeOut = (size_t)size;
    return 1;
}
