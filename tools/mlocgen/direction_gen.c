#include <stdio.h>
#include <stdlib.h>
#include <string.h>

enum
{
    // scriptMetadata.txt lists about 170 scripts.
    maxScripts = 512,
    rtlField = 6,
};

// Whether text is a script code: an uppercase letter and three lowercase.
static bool ScriptCode(const char* text, size_t length)
{
    if (length != 4 || text[0] < 'A' || text[0] > 'Z')
    {
        return false;
    }
    for (size_t i = 1; i < 4; i++)
    {
        if (text[i] < 'a' || text[i] > 'z')
        {
            return false;
        }
    }
    return true;
}

// The field'th ";"-separated field of a line, trimmed; false past the
// line's last field.
static bool LineField(const char* line, size_t lineLength, int field, const char** startOut,
                      size_t* lengthOut)
{
    const char* at = line;
    const char* end = line + lineLength;
    for (int i = 0; i < field; i++)
    {
        const char* semicolon = memchr(at, ';', (size_t)(end - at));
        if (semicolon == nullptr)
        {
            return false;
        }
        at = semicolon + 1;
    }
    const char* stop = memchr(at, ';', (size_t)(end - at));
    stop = stop != nullptr ? stop : end;
    while (at < stop && (*at == ' ' || *at == '\t'))
    {
        at++;
    }
    while (stop > at && (stop[-1] == ' ' || stop[-1] == '\t' || stop[-1] == '\r'))
    {
        stop--;
    }
    *startOut = at;
    *lengthOut = (size_t)(stop - at);
    return true;
}

static int CompareCodes(const void* a, const void* b)
{
    return memcmp(a, b, 4);
}

// The scripts whose RTL field is YES, sorted; 0 and a message on failure.
static int ReadScripts(const char* metadata, char (*codes)[4], char* errorOut, size_t errorCapacity)
{
    int count = 0;
    int line = 0;
    for (const char* at = metadata; *at != '\0';)
    {
        size_t length = strcspn(at, "\n");
        line++;
        const char* code;
        size_t codeLength;
        const char* rtl;
        size_t rtlLength;
        bool blank = strspn(at, " \t\r") >= length;
        if (!blank && at[0] != '#')
        {
            if (!LineField(at, length, 0, &code, &codeLength) ||
                !LineField(at, length, rtlField, &rtl, &rtlLength) || !ScriptCode(code, codeLength))
            {
                snprintf(errorOut, errorCapacity,
                         "scriptMetadata.txt: line %d: no script code or RTL field", line);
                return 0;
            }
            if (rtlLength == 3 && memcmp(rtl, "YES", 3) == 0)
            {
                if (count == maxScripts)
                {
                    snprintf(errorOut, errorCapacity, "scriptMetadata.txt: too many scripts");
                    return 0;
                }
                memcpy(codes[count++], code, 4);
            }
        }
        at += length + (at[length] == '\n' ? 1 : 0);
    }
    if (count == 0)
    {
        snprintf(errorOut, errorCapacity, "scriptMetadata.txt has no script written right to left");
        return 0;
    }
    GenSort(codes, (size_t)count, 4, CompareCodes);
    for (int i = 1; i < count; i++)
    {
        if (memcmp(codes[i - 1], codes[i], 4) == 0)
        {
            snprintf(errorOut, errorCapacity, "scriptMetadata.txt lists %.4s twice", codes[i]);
            return 0;
        }
    }
    return count;
}

int ScriptDirectionsSource(const char* metadata, char** sourceOut, size_t* sourceSizeOut,
                           char* errorOut, size_t errorCapacity)
{
    char codes[maxScripts][4];
    int count = ReadScripts(metadata, codes, errorOut, errorCapacity);
    if (count == 0)
    {
        return 0;
    }
    size_t capacity = 1024 + (size_t)count * 16;
    char* source = malloc(capacity);
    if (source == nullptr)
    {
        snprintf(errorOut, errorCapacity, "out of memory");
        return 0;
    }
    size_t size = 0;
    bool fits = GenPrint(source, capacity, &size, "%s",
                         "// SPDX-License-Identifier: MIT\n"
                         "// Copyright (c) 2026 Sirac Ozmen\n"
                         "//\n"
                         "// The scripts written right to left, from CLDR's\n"
                         "// properties/scriptMetadata.txt, sorted.\n"
                         "// Generated by tools/mlocgen; do not edit.\n"
                         "// clang-format off\n"
                         "\n"
                         "#include \"script_directions.h\"\n"
                         "\n"
                         "const char mlocRightToLeftScripts[][4] = {\n");
    for (int i = 0; fits && i < count; i++)
    {
        fits = GenPrint(source, capacity, &size, "    {'%c', '%c', '%c', '%c'},\n", codes[i][0],
                        codes[i][1], codes[i][2], codes[i][3]);
    }
    fits = fits && GenPrint(source, capacity, &size,
                            "};\n\nconst uint32_t mlocRightToLeftScriptCount = %d;\n", count);
    if (!fits)
    {
        snprintf(errorOut, errorCapacity, "script_directions.c does not fit %zu bytes", capacity);
        free(source);
        return 0;
    }
    *sourceOut = source;
    *sourceSizeOut = size;
    return 1;
}

int GenerateScriptDirections(const char* commonDirectory, char** sourceOut, size_t* sourceSizeOut,
                             char* errorOut, size_t errorCapacity)
{
    char path[4096];
    snprintf(path, sizeof(path), "%s/properties/scriptMetadata.txt", commonDirectory);
    FILE* file = fopen(path, "rb");
    if (file == nullptr)
    {
        snprintf(errorOut, errorCapacity, "cannot open %s", path);
        return 0;
    }
    size_t capacity = 1 << 16;
    char* text = malloc(capacity);
    size_t length = text != nullptr ? fread(text, 1, capacity - 1, file) : 0;
    bool whole = text != nullptr && feof(file);
    fclose(file);
    if (!whole)
    {
        free(text);
        snprintf(errorOut, errorCapacity, "%s is unreadable or past 64 KiB", path);
        return 0;
    }
    text[length] = '\0';
    int ok = ScriptDirectionsSource(text, sourceOut, sourceSizeOut, errorOut, errorCapacity);
    free(text);
    return ok;
}
