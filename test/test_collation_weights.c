static void TestAgainstIcu(void)
{
    size_t wrong = 0;
    for (size_t i = 0; i < sizeof(s_icu) / sizeof(s_icu[0]); i++)
    {
        const IcuCase* c = &s_icu[i];
        CollationWeights w;
        if (c->level == 1)
        {
            CollationWeightsForPrimary(&w, c->compressible);
        }
        else if (c->level == 2)
        {
            CollationWeightsForSecondary(&w);
        }
        else
        {
            CollationWeightsForTertiary(&w);
        }
        bool fits = CollationWeightsAllocate(&w, c->lower, c->upper, c->n);
        uint64_t hash = 0;
        uint32_t first = 0;
        uint32_t last = 0;
        for (int32_t k = 0; fits && k < c->n; k++)
        {
            last = CollationWeightsNext(&w);
            first = k == 0 ? last : first;
            hash = hash * 1000003U + last;
        }
        bool same =
            fits == c->fits && (!fits || (first == c->first && last == c->last && hash == c->hash));
        wrong += same ? 0 : 1;
    }
    CHECK(wrong == 0, "245 allocations of each level as ICU4C 79 makes them");
}

static void TestRefusals(void)
{
    CollationWeights w;
    CollationWeightsForPrimary(&w, false);
    CHECK(!CollationWeightsAllocate(&w, 0x31000000, 0x30000000, 1) &&
              !CollationWeightsAllocate(&w, 0x30000000, 0x30000000, 1) &&
              !CollationWeightsAllocate(&w, 0x30000000, 0x30050000, 1) &&
              !CollationWeightsAllocate(&w, 0x30000000, 0x31000000, 1) &&
              !CollationWeightsAllocate(&w, 0x30100000, 0x30120000, 70000),
          "limits out of order or equal, an upper limit extending the lower, adjacent "
          "one-byte weights, and more weights than four bytes hold, refused");
}

int main(void)
{
    TestPrimaries();
    TestLowerLevels();
    TestRefusals();
    TestAgainstIcu();
    return s_failures == 0 ? 0 : 1;
}
