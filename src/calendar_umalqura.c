enum
{
    firstYear = 1300,
    lastYear = 1600,
    // A year's bits: bit m - 1 set for a month m of 30 days, and in the
    // top four bits its first day's offset from the tabular civil
    // calendar's, plus one.
    lengthBits = 0x0FFF,
    offsetShift = 12,
};

