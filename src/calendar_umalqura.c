static bool InTable(int64_t year)
{
    return year >= firstYear && year <= lastYear;
}

static uint16_t Bits(int64_t year)
{
    return s_years[year - firstYear];
}

static int64_t YearStart(int64_t year)
{
    int64_t tabular = mlocArithmeticToDay(mloc_calendarIslamicCivil, year, 1, 1);
    return InTable(year) ? tabular + (Bits(year) >> offsetShift) - 1 : tabular;
}

bool mlocUmalquraLeap(int64_t year)
{
    if (!InTable(year))
    {
        return mlocArithmeticLeap(mloc_calendarIslamicCivil, year);
    }
    uint32_t longMonths = 0;
    for (uint32_t bits = Bits(year) & lengthBits; bits != 0; bits &= bits - 1)
    {
        longMonths++;
    }
    return longMonths == 7;
}

uint32_t mlocUmalquraDaysInMonth(int64_t year, uint32_t month)
{
    return InTable(year) ? 29u + ((uint32_t)Bits(year) >> (month - 1) & 1u)
                         : mlocArithmeticDaysInMonth(mloc_calendarIslamicCivil, year, month);
}

int64_t mlocUmalquraToDay(int64_t year, uint32_t month, uint32_t day)
{
    if (!InTable(year))
    {
        return mlocArithmeticToDay(mloc_calendarIslamicCivil, year, month, day);
    }
    int64_t fixed = YearStart(year) + day - 1;
    for (uint32_t m = 1; m < month; m++)
    {
        fixed += mlocUmalquraDaysInMonth(year, m);
    }
    return fixed;
}

CalendarDate mlocUmalquraFromDay(int32_t day)
{
    CalendarDate tabular = mlocArithmeticFromDay(mloc_calendarIslamicCivil, day);
    int64_t year = tabular.year;
    if (!InTable(year))
    {
        return tabular;
    }
    // A table year starts within a day of the tabular one, and the first
    // and last years start and end with it.
    if (YearStart(year) > day)
    {
        year--;
    }
    else if (year < lastYear && YearStart(year + 1) <= day)
    {
        year++;
    }
    int64_t left = day - YearStart(year);
    uint32_t month = 1;
    while (left >= mlocUmalquraDaysInMonth(year, month))
    {
        left -= mlocUmalquraDaysInMonth(year, month);
        month++;
    }
    return (CalendarDate){(int32_t)year, (uint8_t)month, (uint8_t)(left + 1)};
}
