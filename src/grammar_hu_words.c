const HungarianWord* mlocHungarianFindWord(const uint8_t* word, size_t length)
{
    size_t low = 0;
    size_t high = sizeof(s_words) / sizeof(s_words[0]);
    while (low < high)
    {
        size_t mid = low + (high - low) / 2;
        const char* key = s_words[mid].key;
        size_t n = strlen(key);
        int order = memcmp(key, word, n < length ? n : length);
        if (order == 0)
        {
            order = n < length ? -1 : n > length ? 1 : 0;
        }
        if (order == 0)
        {
            return &s_words[mid];
        }
        if (order < 0)
        {
            low = mid + 1;
        }
        else
        {
            high = mid;
        }
    }
    return nullptr;
}
